// Writes the iOS and Android string files from strings/en.json, where Ridgeline's text is edited.
// `node scripts/strings.mjs --check`, which CI runs, fails when a platform file is not what this script writes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'strings/en.json'), 'utf8'));
const keys = Object.keys(catalog).sort();
for (const key of keys) {
  if (!/^[a-z_]+(\.[a-z_]+)*$/.test(key)) throw Error(`strings: ${key} is not a valid key (lowercase words joined by dots)`);
  if (typeof catalog[key] !== 'string' || catalog[key] === '') throw Error(`strings: ${key} needs a text`);
}
// The files carry a digest of the catalog they came from, so a copy edited by hand is told apart from a written one.
const source = createHash('sha256').update(JSON.stringify(keys.map(key => [key, catalog[key]]))).digest('hex').slice(0, 12);
const note = 'Generated by scripts/strings.mjs from strings/en.json. Do not edit: change strings/en.json and run `node scripts/strings.mjs`.';
const swift = text => text.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
const xml = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll("'", "\\'").replaceAll('"', '\\"');
const files = {
  'ios/Trailhead/en.lproj/Localizable.strings': [`/* ${note} */`, `/* source: ${source} */`, '',
    ...keys.map(key => `"${key}" = "${swift(catalog[key])}";`), ''].join('\n'),
  'android/app/src/main/res/values/strings.xml': ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${note} -->`, `<!-- source: ${source} -->`,
    '<resources>', ...keys.map(key => `    <string name="${key.replaceAll('.', '_')}">${xml(catalog[key])}</string>`), '</resources>', ''].join('\n'),
};
if (process.argv.includes('--check')) {
  const stale = Object.keys(files).filter(path => readFileSync(join(root, path), 'utf8') !== files[path]);
  for (const path of stale) console.error(`strings: ${path} is out of date; run node scripts/strings.mjs`);
  if (stale.length) process.exit(1);
  console.log(`strings: up to date (${keys.length} strings, source ${source})`);
} else {
  for (const [path, text] of Object.entries(files)) writeFileSync(join(root, path), text);
  console.log(`strings: wrote ${Object.keys(files).length} files (${keys.length} strings, source ${source})`);
}
JS
